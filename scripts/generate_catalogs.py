"""Generate static, type-checker-friendly catalogs from catalogs.json."""

import argparse
import json
import keyword
from pathlib import Path
from typing import Any

import black

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "scripts" / "catalogs.json"
OUTPUT = ROOT / "anipics" / "_catalogs"


def _identifier(name: str) -> None:
    if not name.isidentifier() or keyword.iskeyword(name):
        raise ValueError(f"Invalid Python identifier: {name!r}")


def _render_group(
    name: str,
    members: dict[str, Any],
    lines: list[str],
    leaves: dict[str, str],
    prefix: str = "",
    depth: int = 0,
) -> None:
    _identifier(name)
    path = f"{prefix}.{name}" if prefix else name
    if not isinstance(members, dict) or not members:
        raise ValueError(f"Group {path!r} must be a nonempty mapping")
    indent = "    " * depth
    lines.append(f"{indent}class {name}:")
    for member, value in members.items():
        _identifier(member)
        if isinstance(value, dict):
            _render_group(member, value, lines, leaves, path, depth + 1)
        elif isinstance(value, str):
            leaves[f"{path}.{member}"] = value
            lines.append(f"{indent}    {member}: Final = {value!r}")
        else:
            raise ValueError(f"Catalog leaf {path}.{member} must be a string")
    lines.append("")


def render_catalog(data: dict[str, Any]) -> str:
    """Render one provider entry, preserving group, leaf, and reference order."""
    groups = data["groups"]
    group_lines: list[str] = []
    leaves: dict[str, str] = {}
    for name, members in groups.items():
        _render_group(name, members, group_lines, leaves)

    def group_paths(name: str) -> list[str]:
        if name not in groups:
            raise ValueError(f"Unknown catalog group: {name!r}")
        return [path for path in leaves if path.startswith(f"{name}.")]

    def require_leaf(path: str) -> None:
        if path not in leaves:
            raise ValueError(f"Unknown catalog leaf reference: {path!r}")

    lines = [
        "# Generated by scripts/generate_catalogs.py from scripts/catalogs.json.",
        "# Do not edit this file directly.",
        "from typing import Final, Literal, TypeAlias",
        "",
    ]
    for name, alias in data["aliases"].items():
        _identifier(name)
        paths = group_paths(alias["group"])
        excluded = {f"{alias['group']}.{path}" for path in alias.get("exclude", [])}
        for path in excluded:
            require_leaf(path)
        values = [repr(leaves[path]) for path in paths if path not in excluded]
        if not values:
            raise ValueError(f"Alias {name!r} must contain at least one catalog leaf")
        lines.append(f"{name}: TypeAlias = Literal[{', '.join(values)}]")
    lines.extend(["", *group_lines])

    for name, references in data.get("tuples", {}).items():
        _identifier(name)
        if isinstance(references, str):
            paths = group_paths(references)
        elif isinstance(references, list):
            paths = references
        else:
            raise ValueError(f"Tuple {name!r} must reference a group or list of leaves")
        for path in paths:
            require_leaf(path)
        lines.append(f"{name}: Final = (")
        lines.extend(f"    {path}," for path in paths)
        lines.append(")")

    return black.format_str(
        "\n".join(lines) + "\n",
        mode=black.Mode(target_versions={black.TargetVersion.PY310}),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="List stale or missing generated modules without writing them",
    )
    args = parser.parse_args()
    catalogs = json.loads(SOURCE.read_text(encoding="utf-8"))
    outputs: dict[Path, bytes] = {}
    for provider, data in catalogs.items():
        _identifier(provider)
        try:
            outputs[OUTPUT / f"{provider}.py"] = render_catalog(data).encode("utf-8")
        except (KeyError, TypeError, ValueError) as error:
            parser.error(f"{provider}: {error}")

    stale = False
    for path, expected in outputs.items():
        exists = path.exists()
        if exists and path.read_bytes() == expected:
            continue
        if args.check:
            state = "stale" if exists else "missing"
            print(f"{state}: {path.relative_to(ROOT).as_posix()}")
            stale = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
            print(f"wrote: {path.relative_to(ROOT).as_posix()}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
